const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const Voice=require('./static/voice.js');
const levels=[];let requests=0;
const voice=new Voice({level:value=>levels.push(value),canInterrupt:()=>false,detect:()=>{requests++;},status:()=>{}});
voice.active=true;voice.suspended=true;
voice.frame(new Int16Array(5120).fill(16384),0);
assert.equal(levels[0],.5);assert.equal(requests,0);
voice.processing=true;voice.frame(new Int16Array(5120),0);
assert.equal(levels[1],0,'capture diagnostics continue while processing');
voice.stop();voice.frame(new Int16Array(5120),voice.generation);
assert.equal(levels.length,2,'stopped capture cannot report fresh frames');
const source=fs.readFileSync(__dirname+'/static/app.js','utf8');
const context={Date};vm.createContext(context);
vm.runInContext(source.slice(0,source.indexOf('(() => {')),context);
for(let i=0;i<40;i++)context.voiceDiagnostic('Playback','event '+i);
assert.equal(context.voiceDiagnostic.entries.length,30);
assert.equal(context.voiceDiagnostic.latest.Playback,'event 39');
assert.deepEqual(Object.keys(context.voiceDiagnostic.entries[0]),['time','stage','message']);
console.log('PASS: live RMS during playback/processing, no monitoring requests, stopped capture and bounded metadata.');
