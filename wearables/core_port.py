"""Later implementations delegate to the existing JARVIS services, not a new brain."""
from typing import Protocol
from .contracts import Audio, Image
from .output import EncodedAudio


class CorePort(Protocol):
    async def transcribe(self, audio: Audio) -> str: ...
    async def respond(self, text: str, image: Image | None = None) -> str: ...
    async def describe(self, text: str, image: Image) -> str: ...
    async def synthesize(self, text: str) -> Audio | EncodedAudio: ...
